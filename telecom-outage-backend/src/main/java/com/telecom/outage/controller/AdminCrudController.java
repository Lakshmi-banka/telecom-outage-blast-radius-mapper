package com.telecom.outage.controller;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;
import java.util.*;

/**
 * Administrative CRUD for the remaining normalized tables.
 * Table and column names are always checked against an explicit allow-list before SQL is built.
 * Relationship columns are supplied as *_id values.
 */
@RestController
@RequestMapping("/api/admin/data")
@PreAuthorize("hasRole('ADMIN')")
public class AdminCrudController {
    private final JdbcTemplate jdbc;
    private static final Map<String, String> TABLES = Map.ofEntries(
        Map.entry("roles","role_id"), Map.entry("users","user_id"),
        Map.entry("components","component_id"), Map.entry("component_dependencies","dependency_id"),
        Map.entry("services","service_id"), Map.entry("service_components","service_component_id"),
        Map.entry("alarms","alarm_id"), Map.entry("incidents","incident_id"),
        Map.entry("incident_affected_components","incident_affected_component_id"),
        Map.entry("incident_affected_services","incident_affected_service_id"),
        Map.entry("restoration_history","restoration_id"), Map.entry("audit_logs","audit_id")
    );
    private static final Set<String> COMPOSITE = Set.of("incident_alarms");
    public AdminCrudController(JdbcTemplate jdbc) { this.jdbc = jdbc; }

    @GetMapping("/{table}")
    public List<Map<String,Object>> list(@PathVariable String table) {
        check(table);
        List<Map<String,Object>> rows = jdbc.queryForList("SELECT * FROM " + table + " ORDER BY 1");
        return sanitize(table, rows);
    }

    @GetMapping("/{table}/{id}")
    public Map<String,Object> get(@PathVariable String table, @PathVariable long id) {
        String pk = pk(table);
        List<Map<String,Object>> rows = jdbc.queryForList("SELECT * FROM " + table + " WHERE " + pk + " = ?", id);
        if (rows.isEmpty()) throw new NoSuchElementException(table + " record not found");
        return sanitize(table, rows).get(0);
    }

    @PostMapping("/{table}")
    public Map<String,Object> create(@PathVariable String table, @RequestBody Map<String,Object> body) {
        check(table);
        if (COMPOSITE.contains(table)) throw new IllegalArgumentException("Use the dedicated relationship endpoint for " + table);
        String pk = pk(table);
        Map<String,Object> values = new LinkedHashMap<>(body);
        values.remove(pk);
        if (table.equals("users") && values.containsKey("password_hash"))
            throw new IllegalArgumentException("Use password field; password hashes are generated by the API");
        if (table.equals("users") && values.containsKey("password")) {
            values.put("password_hash", new org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder()
                .encode(String.valueOf(values.remove("password"))));
        }
        validateColumns(table, values);
        if (values.isEmpty()) throw new IllegalArgumentException("At least one field is required");
        String columns = String.join(",", values.keySet());
        String marks = String.join(",", values.keySet().stream().map(this::placeholder).toList());
        Object[] args = values.entrySet().stream().map(e -> normalize(e.getKey(), e.getValue())).toArray();
        jdbc.update("INSERT INTO " + table + " (" + columns + ") VALUES (" + marks + ")", args);
        Long id = jdbc.queryForObject("SELECT currval(pg_get_serial_sequence(?, ?))", Long.class, table, pk);
        return get(table, id);
    }

    @PutMapping("/{table}/{id}")
    public Map<String,Object> update(@PathVariable String table, @PathVariable long id,
                                     @RequestBody Map<String,Object> body) {
        String pk = pk(table);
        Map<String,Object> values = new LinkedHashMap<>(body);
        values.remove(pk);
        if (table.equals("users") && values.containsKey("password_hash"))
            throw new IllegalArgumentException("Use password field; password hashes are generated by the API");
        if (table.equals("users") && values.containsKey("password")) {
            values.put("password_hash", new org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder()
                .encode(String.valueOf(values.remove("password"))));
        }
        validateColumns(table, values);
        if (values.isEmpty()) throw new IllegalArgumentException("No updatable fields supplied");
        String set = String.join(",", values.keySet().stream().map(c -> c + " = " + placeholder(c)).toList());
        List<Object> args = new ArrayList<>(values.entrySet().stream().map(e -> normalize(e.getKey(), e.getValue())).toList()); args.add(id);
        int changed = jdbc.update("UPDATE " + table + " SET " + set + " WHERE " + pk + " = ?", args.toArray());
        if (changed == 0) throw new NoSuchElementException(table + " record not found");
        return get(table, id);
    }

    @DeleteMapping("/{table}/{id}")
    public Map<String,Object> delete(@PathVariable String table, @PathVariable long id) {
        String pk = pk(table);
        int changed = jdbc.update("DELETE FROM " + table + " WHERE " + pk + " = ?", id);
        if (changed == 0) throw new NoSuchElementException(table + " record not found");
        return Map.of("deleted", true, "table", table, "id", id);
    }


    private String placeholder(String column) {
        return switch (column) {
            case "details" -> "?::jsonb";
            case "ip_address" -> "?::inet";
            case "created_at", "updated_at", "occurred_at", "acknowledged_at", "cleared_at",
                 "started_at", "resolved_at", "linked_at", "detected_at", "performed_at" -> "?::timestamp";
            default -> "?";
        };
    }
    private Object normalize(String column, Object value) {
        if (value == null) return null;
        if (column.equals("details") && value instanceof Map<?,?>)
            try { return new com.fasterxml.jackson.databind.ObjectMapper().writeValueAsString(value); }
            catch (com.fasterxml.jackson.core.JsonProcessingException ex) { throw new IllegalArgumentException("Invalid details JSON"); }
        return value;
    }
    private String pk(String table) {
        check(table);
        if (COMPOSITE.contains(table)) throw new IllegalArgumentException("Composite-key table; use its relationship endpoint");
        return TABLES.get(table);
    }
    private void check(String table) {
        if (!TABLES.containsKey(table) && !COMPOSITE.contains(table))
            throw new IllegalArgumentException("Unsupported table. Allowed: " + TABLES.keySet() + " and incident_alarms");
    }
    private void validateColumns(String table, Map<String,Object> values) {
        check(table);
        Set<String> allowed = new HashSet<>();
        jdbc.query("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=?",
            (org.springframework.jdbc.core.RowCallbackHandler) rs -> {
                allowed.add(rs.getString(1));
            }, table);
        for (String column : values.keySet())
            if (!column.matches("[a-z][a-z0-9_]*") || !allowed.contains(column))
                throw new IllegalArgumentException("Invalid column for " + table + ": " + column);

    }
    private List<Map<String,Object>> sanitize(String table, List<Map<String,Object>> rows) {
        if (!table.equals("users")) return rows;
        for (Map<String,Object> row : rows) row.remove("password_hash");
        return rows;
    }
}
